export const LOCALES = ["en", "fr"] as const;
export type Lang = (typeof LOCALES)[number];

/** Origin without a trailing slash (config.baseUrl may or may not have one). */
export const siteUrl = metaData.baseUrl.replace(/\/+$/, "");
export const abs = (path = "") => `${siteUrl}${path && !path.startsWith("/") ? `/${path}` : path}`;

export const OG_LOCALE: Record<Lang, string> = { en: "en_US", fr: "fr_FR" };

