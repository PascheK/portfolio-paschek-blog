/** 1200×630 share image generated by app/[lang]/og/route.tsx. */
export function ogImageUrl(lang: Lang, title: string, eyebrow?: string) {
  const q = new URLSearchParams({ title });
  if (eyebrow) q.set("eyebrow", eyebrow);
  return abs(`/${lang}/og?${q.toString()}`);
}

/** Absolute URL for an image path coming from content frontmatter (/blogs/x.png) or already absolute. */
export const absImage = (src: string) => (/^https?:\/\//.test(src) ? src : abs(src));

type PageMetaInput = {
  lang: Lang;
  /** Path after the locale, "" for the home page, "/blog/my-post" otherwise. */
  path?: string;
  title: string;
  description: string;
  /** Used verbatim as <title> (no "| PascheK" suffix), for the home page. */
  absoluteTitle?: boolean;
  type?: "website" | "article";
  /** Absolute or site-relative image URL. Defaults to a generated share image. */
  image?: string;
  imageEyebrow?: string;
  publishedTime?: string;
  modifiedTime?: string;
  tags?: string[];
  /** Locales that really have this page (default: all). Drives hreflang. */
  languages?: Lang[];
};

/**
 * Per-page metadata: canonical, hreflang, Open Graph and Twitter card, all pointing at the same
 * canonical URL so Google consolidates signals and shows the right language to each searcher.
 */
export function pageMeta({
  lang,
  path = "",
  title,
  description,
  absoluteTitle = false,
  type = "website",
  image,
  imageEyebrow,
  publishedTime,
  modifiedTime,
  tags,
  languages = [...LOCALES],
}: PageMetaInput): Metadata {
  const url = abs(`/${lang}${path}`);
  const img = image ? absImage(image) : ogImageUrl(lang, title, imageEyebrow);
  // Only the generated image is known to be 1200×630; don't declare sizes for content images.
  const size = image ? {} : { width: 1200, height: 630 };
  const hreflang: Record<string, string> = Object.fromEntries(languages.map((l) => [l, abs(`/${l}${path}`)]));
  hreflang["x-default"] = abs(`/${languages.includes("en") ? "en" : languages[0]}${path}`);

  return {
    title: absoluteTitle ? { absolute: title } : title,
    description,
    alternates: { canonical: url, languages: hreflang },
    openGraph: {
      type,
      url,
      title,
      description,
      siteName: "PascheK",
      locale: OG_LOCALE[lang],
      alternateLocale: languages.filter((l) => l !== lang).map((l) => OG_LOCALE[l]),
      images: [{ url: img, ...size, alt: title }],
      ...(type === "article"
        ? { publishedTime, modifiedTime: modifiedTime ?? publishedTime, authors: [metaData.name], tags }
        : {}),
    },
    twitter: { card: "summary_large_image", title, description, images: [img] },
  };
}

/** "5:11" / "1:02:03" → ISO 8601 duration ("PT5M11S"), for VideoObject. */
export function isoDuration(text?: string): string | undefined {
  if (!text) return undefined;
  const p = text.split(":").map(Number);
  if (p.some((n) => Number.isNaN(n)) || p.length > 3) return undefined;
  const [h, m, s] = p.length === 3 ? p : [0, ...(p.length === 2 ? p : [0, p[0]])];
  return `PT${h ? `${h}H` : ""}${m ? `${m}M` : ""}${s || (!h && !m) ? `${s}S` : ""}`;
}
